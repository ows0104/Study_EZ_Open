const { test } = require('node:test');
const assert = require('node:assert/strict');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const fs = require('node:fs');
const path = require('node:path');
const base = process.env.CATALOG_TEST_URL || 'http://127.0.0.1:5198/tests/bank-catalog.html';
const output = path.resolve(__dirname, '../../work/bank-catalog-20261016');

test('slide catalog: navigation, search, all card formats, lazy answers, retry, images and mobile', async () => {
  fs.mkdirSync(output, { recursive: true });
  const browser = await chromium.launch({ headless: true, channel: 'chrome' });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const card = number => page.getByRole('article', { name: `${number}번 문제`, exact: true });
  const reveal = number => card(number).getByRole('button', { name: '정답·해설 보기 ↓', exact: true });
  try {
    await page.goto(base);
    await page.getByText('7 / 7문항 · 슬라이드 순', { exact: true }).waitFor();
    assert.deepEqual(await page.locator('.catalog-group > h2').allTextContents(), ['PDF 2쪽2문항', 'PDF 9쪽1문항', 'PDF 12쪽1문항', 'PDF 20쪽2문항', '슬라이드 위치 미지정1문항']);
    assert.equal((await page.evaluate(() => window.catalogTest.requests)).length, 1);
    assert.equal(await page.locator('.catalog-answer:visible').count(), 0);
    await page.getByRole('navigation', { name: '슬라이드별 문제 이동' }).getByRole('link', { name: 'PDF 20쪽' }).click();
    assert.equal(await page.evaluate(() => location.hash), '#catalog-slide-20');
    const search = page.getByRole('searchbox', { name: '문제 검색' });
    await search.fill('Q3');
    await page.getByText('1 / 7문항 · 슬라이드 순', { exact: true }).waitFor();
    assert.equal(await card(3).count(), 1);
    await search.fill('없는 검색어');
    await page.getByText('조건에 맞는 문제가 없습니다.').waitFor();
    await page.getByRole('button', { name: '모든 문제 보기', exact: true }).click();
    await page.getByRole('combobox', { name: '보기', exact: true }).selectOption('suspended');
    assert.equal(await page.locator('.catalog-card').count(), 1);
    assert.match(await card(2).innerText(), /비활성화/);
    await page.getByRole('combobox', { name: '보기', exact: true }).selectOption('personal');
    assert.equal(await page.locator('.catalog-card').count(), 1);
    assert.match(await card(7).innerText(), /내 문제/);
    await page.getByRole('combobox', { name: '보기', exact: true }).selectOption('all');
    await reveal(2).click();
    await card(2).getByText('예시 정답', { exact: true }).waitFor();
    await card(2).getByRole('button', { name: '정답·해설 접기 ↑' }).click();
    assert.match(await card(2).innerText(), /\[ 1 \]/);
    await reveal(3).click();
    await card(3).getByRole('region', { name: '선지별 해설' }).waitFor();
    assert.equal(await card(3).locator('.bank-choice-score').count(), 0);
    for (const number of [1, 4, 5, 6, 7]) {
      await reveal(number).click();
      await card(number).getByRole('region', { name: '해설', exact: true }).waitFor();
    }
    await card(4).getByText('문항 검수 기록', { exact: true }).click();
    await card(4).getByText('남은 검토 사항', { exact: false }).waitFor();
    await card(1).getByRole('button', { name: '정답·해설 접기 ↑' }).click();
    await page.evaluate(() => { window.catalogTest.failAnswer = true; });
    await reveal(1).click();
    await card(1).getByRole('alert').waitFor();
    await page.evaluate(() => { window.catalogTest.failAnswer = false; });
    await card(1).getByRole('button', { name: '다시 시도', exact: true }).click();
    await card(1).getByRole('region', { name: '해설', exact: true }).waitFor();
    await page.getByRole('button', { name: '필기 PDF 2쪽 크게 보기', exact: true }).click();
    await page.getByRole('dialog').waitFor();
    await page.keyboard.press('Escape');
    assert.equal(await page.getByRole('dialog').count(), 0);
    await page.evaluate(() => window.scrollTo(0, 0));
    await page.screenshot({ path: path.join(output, 'desktop.png'), fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.screenshot({ path: path.join(output, 'mobile.png'), fullPage: true });
    await card(1).getByRole('button', { name: '정답·해설 접기 ↑' }).click();
    await page.evaluate(() => { window.catalogTest.stale = true; });
    await reveal(1).click();
    await card(1).getByRole('alert').waitFor();
    await card(1).getByRole('button', { name: '목록 새로고침', exact: true }).click();
    await page.waitForFunction(() => [...document.querySelectorAll('.catalog-answer')].every(element => element.hidden));
    await page.getByText('7 / 7문항 · 슬라이드 순', { exact: true }).waitFor();
    assert.equal(await page.locator('.catalog-answer:visible').count(), 0);
    assert.ok((await page.evaluate(() => window.catalogTest.requests)).every(call => call.method === 'GET'));
    await page.evaluate(() => { window.catalogTest.failList = true; });
    await page.getByRole('button', { name: '목록 새로고침', exact: true }).click();
    await page.getByRole('alert').waitFor();
    await page.evaluate(() => { window.catalogTest.failList = false; });
    await page.getByRole('button', { name: '다시 불러오기', exact: true }).click();
    await page.getByText('7 / 7문항 · 슬라이드 순', { exact: true }).waitFor();
    await page.goto(base + '?empty');
    await page.getByText('등록된 문제가 없습니다.').waitFor();
    assert.deepEqual(errors, []);
  } finally { await browser.close(); }
});
