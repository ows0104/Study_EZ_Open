"""파일명 → 강의명 → 덱 이름.

이 값이 **덱의 정체성**이다. 덱 이름이 흔들리면 Anki 에 덱이 하나 더 생기는 것으로
조용히 드러난다 — 그래서 여기에 묶어 둔다.

강의명의 기본값은 **파일제목 원문**이다. 그래서 작년 필기본으로 만든 예습 덱과 올해
필기본으로 만든 복습 덱은 저절로는 한 노드에 서지 않는다. 모으려면 양쪽에 `--lecture` 로
같은 값을 준다 — 그 두 갈래를 아래에서 둘 다 고정해 둔다.

`clean_lecture_name` 은 이제 덱 이름이 아니라 **족보 조각 대조**(`find_jokbo`)가 쓴다.
거기서는 파일명을 깎는 것이 검색 보조일 뿐이라 성격이 다르다.

실제 아카이브 파일명에는 필기자 실명이 들어 있어 여기 옮기지 않는다.
아래는 같은 꼴로 지어낸 이름이다.
"""

from pathlib import Path

import pytest

from quizgen.pack import clean_lecture_name, lecture_of
from quizgen.prequiz.run import deck_of as pre_deck_of
from quizgen.run import deck_of, lecture_id_of


@pytest.mark.parametrize("stem,want", [
    # 날짜·교시 대괄호를 뗀다
    ("[260820_03]소아질환의 병태생리(2)", "소아질환의 병태생리(2)"),
    ("[260820_03] 소아질환의 병태생리(2)", "소아질환의 병태생리(2)"),
    # 교수 이름 괄호를 뗀다. 회차 괄호는 제목의 일부라 남긴다
    ("면역병리(1)(가나다)", "면역병리(1)"),
    ("면역병리(1)(가나다라마바)", "면역병리(1)"),
    # 필기자·판번호 꼬리를 뗀다
    ("병리학 소개_가나다v1", "병리학 소개"),
    ("병리학 소개_가나다_v2", "병리학 소개"),
    ("병리학 소개_가나다v3 (1)", "병리학 소개"),
    # 셋이 한꺼번에
    ("[260812_01]병리학 소개(가나다)_라마바v1", "병리학 소개"),
    # 뗄 것이 없으면 그대로
    ("만성염증의 병태생리", "만성염증의 병태생리"),
])
def test_clean_lecture_name(stem, want):
    assert clean_lecture_name(stem) == want


def test_강의명의_기본값은_파일제목_원문이다():
    """날짜·교시·교수·필기자를 떼지 않는다. 확장자만 뗀다."""
    f = Path("[250821_02]순환장애의 병태생리(1)(가나다)_라마바v2.pdf")
    assert lecture_of(f) == "[250821_02]순환장애의 병태생리(1)(가나다)_라마바v2"


def test_파일명이_다르면_덱_노드도_갈린다():
    """작년 파일과 올해 파일은 저절로는 한 노드에 서지 않는다. 알고 쓰는 값이다."""
    last = lecture_of(Path("[250821_02]순환장애의 병태생리(1)(가나다)_라마바v2.pdf"))
    this = lecture_of(Path("[260821_01]순환장애의 병태생리(1)(가나다)_사아자v1.pdf"))
    assert last != this


def test_lecture_를_같이_주면_한_노드에_모인다():
    """예습 덱이 복습 덱과 한 노드에 서려면 이것이 성립해야 한다."""
    node = "순환장애의 병태생리(1)"
    assert pre_deck_of(node, "병리학") == "병리학::순환장애의 병태생리(1)::예습"
    assert deck_of(node, "병리학") == "병리학::순환장애의 병태생리(1)"


def test_강의_ID_는_해마다_다르다():
    """덱 노드는 모이지만 guid 씨앗은 갈려야 노트가 안 섞인다."""
    last = lecture_id_of(Path("[250821_02]순환장애의 병태생리(1)(가나다)_라마바v2.pdf"))
    this = lecture_id_of(Path("[260821_01]순환장애의 병태생리(1)(가나다)_사아자v1.pdf"))
    assert last == "p250821_02" and this == "p260821_01"


def test_제목이_대괄호뿐이어도_그대로_쓴다():
    """빈 덱 이름을 내느니 지저분한 이름이 낫다."""
    assert deck_of(lecture_of(Path("[260812_01].pdf")), "병리학") == "병리학::[260812_01]"


def test_덱은_과목과_강의_두_마디다():
    """마디가 늘면 Anki 에서 엉뚱한 깊이에 덱이 선다.

    (Windows 파일명에는 `:` 가 못 들어가므로 `::` 치환은 방어용이고 여기서 재현할 수 없다.)
    """
    name = lecture_of(Path("[260821_03]종양의 병태 생리 (1) 종양의 정의 및 분류(가나다)_라마바v1.pdf"))
    assert deck_of(name, "병리학").split("::") == [
        "병리학", "[260821_03]종양의 병태 생리 (1) 종양의 정의 및 분류(가나다)_라마바v1"]


def test_과목이_비면_앞머리를_안_붙인다():
    assert deck_of("병리학 소개", "") == "병리학 소개"
    assert pre_deck_of("병리학 소개", "") == "병리학 소개::예습"


def test_아무것도_안_주면_과목과_파일제목으로_선다():
    """`--subject`·`--lecture` 를 안 주면 `과목::<파일제목 원문>`.

    복습은 여기에 `::강의록`·`::기출` 이, 예습은 `::예습` 이 붙는다.
    """
    name = lecture_of(Path("[260812_01]병리학 소개(가나다)_라마바v1.pdf"))
    node = "과목::[260812_01]병리학 소개(가나다)_라마바v1"
    assert deck_of(name, "과목") == node
    assert pre_deck_of(name, "과목") == node + "::예습"
