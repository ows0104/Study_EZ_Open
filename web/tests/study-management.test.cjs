const { test } = require('node:test');
const assert = require('node:assert/strict');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const path = require('node:path');
const fs = require('node:fs');
const base = process.env.STUDY_TEST_URL || 'http://127.0.0.1:5197/tests/study-management.html';
const output = process.env.STUDY_TEST_OUTPUT || path.resolve(__dirname, '../../work/study-list-20261106');

test('study list: personal hide/restore, pending events, deletion confirmation, partial errors and 모아풀기', async () => {
  fs.mkdirSync(output, { recursive: true });
  const browser = await chromium.launch({ headless: true, channel: process.env.PLAYWRIGHT_CHANNEL || 'chrome' });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  page.setDefaultTimeout(10000);
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const heading = () => page.getByRole('heading', { name: '강의 목록', exact: true }).waitFor();
  const open = async suffix => { await page.goto(base + suffix, { waitUntil: 'domcontentloaded', timeout: 30000 }); await heading(); };
  // Rows shown in the main list (hidden lectures are excluded).
  const rows = () => page.locator('.list-table .list-row:not(.is-head)').count();
  // Hide/restore, deletion and admin tools live in the folded 「더 보기」 area.
  const more = () => page.locator('.list-more > summary').click();
  const shownTab = () => page.getByRole('button', { name: /^표시 \d+$/ }).click();
  const hiddenTab = () => page.getByRole('button', { name: /^숨긴 강의 \d+$/ }).click();
  const manageAll = () => page.getByRole('checkbox', { name: '표시된 강의 선택', exact: true }).check();
  try {
    await open('');
    assert.equal(await rows(), 3);
    await more();
    await page.getByRole('button', { name: '약력학 숨기기', exact: true }).click();
    await page.getByRole('status').filter({ hasText: '1강의를 숨겼습니다' }).waitFor();
    assert.equal(await rows(), 2);
    assert.equal(await page.getByRole('checkbox', { name: '약력학 선택', exact: true }).count(), 0);
    await page.reload();
    await heading();
    assert.equal(await rows(), 2);
    await more();
    await hiddenTab();
    await page.getByRole('button', { name: '약력학 복원', exact: true }).click();
    await page.getByRole('status').filter({ hasText: '1강의를 복원했습니다' }).waitFor();
    await shownTab();
    assert.equal(await rows(), 3);
    // Pending timetable entries can be hidden before a lecture or quiz exists.
    await page.getByRole('button', { name: '예정 강의 숨기기', exact: true }).click();
    await page.getByRole('status').filter({ hasText: '숨겼습니다' }).waitFor();
    await open('?linked');
    assert.equal(await page.getByRole('checkbox', { name: '예정 강의 선택', exact: true }).count(), 0);
    await more();
    await hiddenTab();
    await page.getByRole('button', { name: '예정 강의 복원', exact: true }).click();
    await page.getByRole('status').filter({ hasText: '1강의를 복원했습니다' }).waitFor();
    await shownTab();
    await manageAll();
    await page.getByRole('button', { name: '선택 3강의 숨기기', exact: true }).click();
    await page.getByRole('status').filter({ hasText: '3강의를 숨겼습니다' }).waitFor();
    assert.equal(await rows(), 0);
    await hiddenTab();
    await manageAll();
    await page.getByRole('button', { name: '선택 3강의 복원', exact: true }).click();
    await page.getByRole('status').filter({ hasText: '3강의를 복원했습니다' }).waitFor();
    await shownTab();
    assert.equal(await rows(), 3);
    await page.getByRole('button', { name: '약력학 퀴즈 삭제', exact: true }).click();
    const dialog = page.getByRole('dialog');
    await dialog.waitFor();
    assert.match(await dialog.innerText(), /모든 사용자가 풀 수 없게 됩니다/);
    assert.deepEqual(await page.evaluate(() => window.studyTest.requests), []);
    await dialog.getByRole('button', { name: '취소', exact: true }).click();
    assert.deepEqual(await page.evaluate(() => window.studyTest.requests), []);
    await page.getByRole('button', { name: '약력학 퀴즈 삭제', exact: true }).click();
    await dialog.getByRole('button', { name: '1강의 퀴즈 삭제', exact: true }).click();
    await page.getByRole('status').filter({ hasText: '퀴즈를 삭제했습니다' }).waitFor();
    assert.deepEqual(await page.evaluate(() => window.studyTest.requests), ['0']);
    assert.equal(await page.getByRole('button', { name: '약력학 퀴즈 삭제', exact: true }).count(), 0);
    assert.equal(await page.getByRole('button', { name: '약력학 숨기기', exact: true }).count(), 1);
    // A lecture without a quiz shows one 「퀴즈 없음」 cell and cannot be picked.
    await page.locator('.list-table .list-row', { hasText: '약력학' }).getByText('퀴즈 없음', { exact: true }).waitFor();
    assert.equal(await page.getByRole('checkbox', { name: '약력학 선택', exact: true }).count(), 0);
    await open('?fail');
    await more();
    await manageAll();
    await page.getByRole('button', { name: '선택 퀴즈 삭제 (2)', exact: true }).click();
    await dialog.getByRole('button', { name: '2강의 퀴즈 삭제', exact: true }).click();
    await dialog.getByRole('alert').waitFor();
    assert.match(await dialog.innerText(), /1강의 삭제 완료/);
    assert.match(await dialog.getByRole('alert').innerText(), /생성 작업이 진행 중/);
    assert.equal(await dialog.getByRole('button', { name: '1강의 퀴즈 삭제', exact: true }).count(), 1);
    await page.screenshot({ path: path.join(output, 'partial-deletion.png'), fullPage: true });
    await dialog.getByRole('button', { name: '닫기', exact: true }).click();
    await open('?student');
    assert.equal(await page.getByRole('button', { name: /퀴즈 삭제/ }).count(), 0);
    await more();
    assert.equal(await page.getByRole('button', { name: /퀴즈 삭제/ }).count(), 0);
    assert.equal(await page.getByRole('button', { name: '약력학 숨기기', exact: true }).count(), 1);
    await open('?hideError');
    await more();
    await page.getByRole('button', { name: '약력학 숨기기', exact: true }).click();
    await page.getByRole('alert').filter({ hasText: '숨김 저장 실패' }).waitFor();
    assert.equal(await rows(), 3);
    await open('');
    // Header labels and the renamed stage (기억 유지 → 저장).
    const head = await page.locator('.list-row.is-head').innerText();
    assert.match(head, /번호[\s\S]*강의[\s\S]*전체[\s\S]*미열람[\s\S]*인지[\s\S]*인출[\s\S]*저장[\s\S]*복습[\s\S]*학습률/);
    assert.equal(await page.getByText('기억 유지').count(), 0);
    await page.waitForFunction(() => /전체 카드\s*200장/.test(document.querySelector('.list-stats')?.innerText ?? ''));
    assert.match(await page.locator('.list-stats').innerText(), /오늘 복습\s*24장/);
    await page.screenshot({ path: path.join(output, 'desktop.png'), fullPage: true });
    await page.setViewportSize({ width: 1000, height: 900 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await page.setViewportSize({ width: 390, height: 844 });
    await page.screenshot({ path: path.join(output, 'mobile.png'), fullPage: true });
    assert.equal(await page.locator('.list-row.is-head .is-stage').first().isVisible(), false);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await page.setViewportSize({ width: 1440, height: 1000 });
    // Selection → floating bar → existing 모아풀기 (BankBatch queue).
    const bar = page.getByRole('region', { name: '모아풀기' });
    assert.equal(await bar.count(), 0);
    await page.getByRole('checkbox', { name: '약력학 선택', exact: true }).click();
    assert.match(await bar.innerText(), /1개 강의\s*선택 · 오늘 복습 12장/);
    await page.getByRole('checkbox', { name: '열린 강의 모두 선택', exact: true }).click();
    assert.match(await bar.innerText(), /2개 강의\s*선택 · 오늘 복습 24장/);
    await bar.getByRole('button', { name: '선택 해제', exact: true }).click();
    assert.equal(await bar.count(), 0);
    await page.getByRole('checkbox', { name: '열린 강의 모두 선택', exact: true }).click();
    await page.screenshot({ path: path.join(output, 'selected.png') });
    assert.deepEqual(errors, []);
    await bar.getByRole('button', { name: '모아풀기', exact: true }).click();
    await page.getByRole('status').filter({ hasText: '2강의 섞어 풀기' }).waitFor();
    await page.getByRole('button', { name: '강의 다시 선택', exact: true }).click();
    await heading();
  } finally { await browser.close(); }
});
